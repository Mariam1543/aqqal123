"""How far does each heuristic overestimate the true cost-to-go?

A heuristic is admissible when h(n) <= h*(n), the true cost from n to the goal.
On an 8-connected grid without obstacles h* is the octile distance, so the
worst case of a distance function is found analytically on a 45-degree diagonal
(dx = dy = k, h* = sqrt(2) k):

* Euclidean                     sqrt(2) k        -> ratio 1        (admissible)
* hybrid (E + M) / 2, Eq. 7     (sqrt(2)+2)/2 k  -> ratio 1.207   (+20.7 %)
* omega * hybrid, Eqs. 6-7      omega <= ln(1+e) = 1.313 for nodes no farther
                                from the goal than the start -> ratio 1.585 (+58.5 %)
* omega * (E + M), V4           -> ratio 3.170

Nodes farther from the goal than the start have d/D > 1, so omega and the
ratio can be larger still. Obstacles only increase h*, so these are upper
bounds of h / h* over obstacle-free directions.

The empirical part computes h* exactly (Dijkstra from the goal) on the
digitised paper maps and reports max h(n) / h*(n) over all reachable cells.

Output: results/paper_maps/admissibility.md
Usage:  python scripts/admissibility.py
"""

from __future__ import annotations

import heapq
import math
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from adaptive_astar import from_paper  # noqa: E402
from adaptive_astar.heuristics import adaptive_weight, euclidean, hybrid, hybrid_sum  # noqa: E402
from adaptive_astar.maps import load_map_set  # noqa: E402

CASES = [("30x30", (2, 2), (28, 28)), ("60x60", (2, 2), (58, 58)), ("100x100", (2, 2), (99, 99))]
OMEGA_MAX = math.log1p(math.e)                       # omega at d = D (the start)
HYBRID_DIAG = (math.sqrt(2) + 2) / 2 / math.sqrt(2)  # hybrid / octile on a diagonal


def analytic_bounds() -> dict[str, float]:
    return {
        "Euclidean (baseline A*)": 1.0,
        "Hybrid alone, Eq. 7": HYBRID_DIAG,
        "omega x hybrid, Eqs. 6-7 as printed": OMEGA_MAX * HYBRID_DIAG,
        "omega x (E+M), V4": OMEGA_MAX * 2 * HYBRID_DIAG,
    }


def cost_to_go(grid, goal) -> dict:
    """Exact h*(n) for every reachable cell (Dijkstra from the goal; moves are symmetric)."""
    dist, pq = {goal: 0.0}, [(0.0, goal)]
    while pq:
        d, c = heapq.heappop(pq)
        if d > dist[c]:
            continue
        for nb, step in grid.neighbors(c):
            if d + step < dist.get(nb, math.inf):
                dist[nb] = d + step
                heapq.heappush(pq, (d + step, nb))
    return dist


def main() -> None:
    maps = load_map_set("paper", ROOT / "maps")
    names = list(analytic_bounds())
    md = ["# Admissibility of the heuristics (h / true cost-to-go)", "",
          "Generated by `scripts/admissibility.py`. A ratio above 1 means the heuristic overestimates "
          "the true remaining cost, so A\\* loses its optimality guarantee.", "",
          "## Analytic worst case (45-degree diagonal, no obstacles)", "",
          "| Heuristic | Worst-case h / h\\* | Overestimate |", "|---|---|---|"]
    for name, r in analytic_bounds().items():
        md.append(f"| {name} | {r:.3f} | {100 * (r - 1):+.1f}% |")
    md += ["", "The bounds with omega hold for nodes no farther from the goal than the start "
           "(omega <= ln(1+e) = 1.313). Nodes behind the start get a larger omega.", "",
           "## Measured on the digitised paper maps (max over all reachable cells)", "",
           "| Map, start -> goal | " + " | ".join(names) + " |", "|---" * (len(names) + 1) + "|"]
    for size, start, goal in CASES:
        grid, s, g = maps[size], from_paper(*start), from_paper(*goal)
        hstar, omega = cost_to_go(grid, g), adaptive_weight(s, g)
        fns = [lambda c: euclidean(c, g), lambda c: hybrid(c, g),
               lambda c: omega(c) * hybrid(c, g), lambda c: omega(c) * hybrid_sum(c, g)]
        worst = [max(f(c) / h for c, h in hstar.items() if h > 0) for f in fns]
        md.append(f"| {size}, {start} -> {goal} | " + " | ".join(f"{w:.3f}" for w in worst) + " |")
        print(md[-1])
    md += ["", "V4 can overestimate the remaining cost about 3x, so its search is close to greedy "
           "best-first search: it expands very few nodes but gives no optimality guarantee."]
    out = ROOT / "results" / "paper_maps"
    out.mkdir(parents=True, exist_ok=True)
    (out / "admissibility.md").write_text("\n".join(md) + "\n")
    print("wrote results/paper_maps/admissibility.md")


if __name__ == "__main__":
    main()
